"use no memo"

import { useState } from "react"
import {
  flexRender,
  type Header,
  type RowData,
  type SortingState,
} from "@tanstack/react-table"
import {
  DndContext,
  KeyboardSensor,
  PointerSensor,
  closestCenter,
  useSensor,
  useSensors,
  type DragEndEvent,
  type DragOverEvent,
  type DragStartEvent,
} from "@dnd-kit/core"
import {
  SortableContext,
  sortableKeyboardCoordinates,
  useSortable,
} from "@dnd-kit/sortable"
import { ArrowUpDown, ChevronUp, ChevronDown, GripVertical } from "lucide-react"
import type {
  ColumnDropPosition,
  TableHeaderProps,
  ColumnMeta,
} from "../../../core/table/types"
import type { DataTableFeatures } from "../../../core/table/features"

/**
 * Extended column meta type
 */
interface ExtendedColumnMeta extends ColumnMeta {
  isAutoGeneratedGroup?: boolean
  hasExplicitGroupHeader?: boolean
}

interface DropTargetState {
  id: string | null
  side: ColumnDropPosition
}

function getColumnLabel<TData extends RowData>(
  header: Header<DataTableFeatures, TData, unknown>
): string {
  const meta = header.column.columnDef.meta as ColumnMeta | undefined
  if (typeof meta?.label === "string") return meta.label
  if (typeof header.column.columnDef.header === "string") {
    return String(header.column.columnDef.header)
  }
  return header.column.id
}

interface HeaderCellProps<TData extends RowData> {
  header: Header<DataTableFeatures, TData, unknown>
  sorting: SortingState
  showHandle: boolean
  isDropTarget: boolean
  dropSide: ColumnDropPosition
  isDraggingSource: boolean
}

/** Left half of the target => insert before, right half => insert after. */
function resolveDropSide(
  activeRect: { left: number; width: number } | null,
  overRect: { left: number; width: number }
): ColumnDropPosition {
  const activeCenterX = activeRect
    ? activeRect.left + activeRect.width / 2
    : overRect.left
  return activeCenterX < overRect.left + overRect.width / 2 ? "before" : "after"
}

function HeaderCell<TData extends RowData>({
  header,
  sorting,
  showHandle,
  isDropTarget,
  dropSide,
  isDraggingSource,
}: HeaderCellProps<TData>) {
  const { attributes, listeners, setNodeRef, isDragging } = useSortable({
    id: header.column.id,
  })

  const column = header.column
  const colId = column.id
  const isSorted = column.getIsSorted()
  const canSort = column.getCanSort()
  const sortingState = sorting
  const isMultiSorted = sortingState.length > 1
  const sortIndex = sortingState.findIndex((s) => s.id === colId)
  const priorityLabel =
    isMultiSorted && sortIndex >= 0 ? ` · priority ${sortIndex + 1}` : ""
  const sortTitle = !canSort
    ? undefined
    : isSorted === "asc"
      ? `Sorted ascending${priorityLabel}`
      : isSorted === "desc"
        ? `Sorted descending${priorityLabel}`
        : "Click to sort"
  const columnLabel = getColumnLabel(header)
  const meta = column.columnDef.meta as ColumnMeta | undefined
  const align =
    meta?.align ??
    (meta?.thClass?.includes("text-right")
      ? "right"
      : meta?.thClass?.includes("text-center")
        ? "center"
        : "left")
  const alignClass =
    align === "right"
      ? "text-right"
      : align === "center"
        ? "text-center"
        : "text-left"
  const thClass = meta?.thClass ?? alignClass
  const justifyClass =
    align === "right"
      ? "justify-end"
      : align === "center"
        ? "justify-center"
        : "justify-start"
  const widthStyle: React.CSSProperties | undefined =
    meta?.width || meta?.maxWidth || meta?.minWidth
      ? {
          ...(meta.width && { width: meta.width }),
          ...(meta.maxWidth && { maxWidth: meta.maxWidth }),
          ...(meta.minWidth && { minWidth: meta.minWidth }),
        }
      : undefined

  const dragging = isDragging || isDraggingSource

  return (
    <th
      ref={setNodeRef}
      colSpan={header.colSpan}
      style={widthStyle}
      className={`relative px-3 py-3.5 text-xs font-semibold uppercase tracking-wide text-table-heading ${thClass} ${
        dragging ? "opacity-60" : ""
      }`}
    >
      <div className={`flex items-center gap-1.5 w-full ${justifyClass}`}>
        {showHandle && (
          <button
            {...attributes}
            {...listeners}
            type="button"
            aria-label={`Reorder ${columnLabel} column`}
            title="Drag to reorder"
            className="shrink-0 cursor-grab active:cursor-grabbing touch-none select-none text-muted-foreground hover:text-foreground transition-colors dark:text-muted-foreground/50 dark:hover:text-muted-foreground"
          >
            <GripVertical size={14} />
          </button>
        )}
        <button
          type="button"
          title={sortTitle}
          aria-label={canSort ? `${columnLabel}: ${sortTitle}` : columnLabel}
          className={`flex items-center gap-1 min-w-0 ${
            canSort ? "cursor-pointer select-none" : ""
          }`}
          onClick={canSort ? column.getToggleSortingHandler() : undefined}
          disabled={!canSort}
        >
          {flexRender(column.columnDef.header, header.getContext())}

          {canSort && (
            <>
              {isSorted === "asc" && (
                <ChevronUp size={14} className="ml-1 shrink-0" />
              )}
              {isSorted === "desc" && (
                <ChevronDown size={14} className="ml-1 shrink-0" />
              )}
              {!isSorted && <ArrowUpDown size={14} className="ml-1 shrink-0" />}
              {isSorted && isMultiSorted && sortIndex >= 0 && (
                <span
                  role="img"
                  aria-label={`Sort priority ${sortIndex + 1}`}
                  className="ml-0.5 inline-flex h-3.5 min-w-3.5 shrink-0 items-center justify-center rounded-full bg-primary px-1 text-[9px] font-bold leading-none text-primary-foreground"
                >
                  {sortIndex + 1}
                </span>
              )}
            </>
          )}
        </button>
      </div>

      {isDropTarget && (
        <span
          aria-hidden="true"
          className={`pointer-events-none absolute top-1 bottom-1 w-0.5 rounded-full bg-primary ${
            dropSide === "before" ? "-left-0.5" : "-right-0.5"
          }`}
        />
      )}
    </th>
  )
}

/**
 * TableHeader component with drag-and-drop column reordering powered by
 * dnd-kit (works with mouse, touch and keyboard). A grip handle starts the
 * drag; hovered headers show a vertical indicator line on the edge where
 * the column will land.
 */
export function TableHeader<TData extends RowData>({
  table,
  onColumnReorder,
}: TableHeaderProps<TData>): React.ReactElement {
  const [activeId, setActiveId] = useState<string | null>(null)
  const [dropTarget, setDropTarget] = useState<DropTargetState>({
    id: null,
    side: "before",
  })

  const sensors = useSensors(
    useSensor(PointerSensor, {
      activationConstraint: { distance: 6 },
    }),
    useSensor(KeyboardSensor, {
      coordinateGetter: sortableKeyboardCoordinates,
    })
  )

  const handleDragStart = (event: DragStartEvent) => {
    setActiveId(String(event.active.id))
  }

  const handleDragOver = (event: DragOverEvent) => {
    if (!event.over) {
      setDropTarget((prev) =>
        prev.id === null ? prev : { id: null, side: prev.side }
      )
      return
    }
    const overId = String(event.over.id)
    const activeIdStr = String(event.active.id)
    if (overId === activeIdStr) {
      setDropTarget((prev) =>
        prev.id === null ? prev : { id: null, side: prev.side }
      )
      return
    }
    const side = resolveDropSide(
      event.active.rect.current.translated ?? null,
      event.over.rect
    )
    setDropTarget((prev) =>
      prev.id === overId && prev.side === side ? prev : { id: overId, side }
    )
  }

  const resetDragState = () => {
    setActiveId(null)
    setDropTarget((prev) =>
      prev.id === null ? prev : { id: null, side: prev.side }
    )
  }

  const handleDragEnd = (event: DragEndEvent) => {
    const sourceId = String(event.active.id)
    const side = dropTarget.side
    resetDragState()
    if (!event.over) return
    const targetId = String(event.over.id)
    if (sourceId === targetId) return
    onColumnReorder?.(sourceId, targetId, side)
  }

  const hasVisibleHeaderLabel = (headerDef: unknown): boolean => {
    if (headerDef === undefined || headerDef === null) return false
    if (typeof headerDef === "string") return headerDef.trim().length > 0
    return true
  }

  return (
    <DndContext
      sensors={sensors}
      collisionDetection={closestCenter}
      onDragStart={handleDragStart}
      onDragOver={handleDragOver}
      onDragEnd={handleDragEnd}
      onDragCancel={resetDragState}
      // dnd-kit renders a hidden live-region div at the provider position;
      // portal it outside the <table> — a <div> under <thead> is invalid HTML
      // and breaks hydration.
      accessibility={{
        container: typeof document === "undefined" ? undefined : document.body,
      }}
    >
      <thead className="bg-secondary/10 border-b border-border dark:bg-muted dark:border-0">
        {table.getHeaderGroups().map((headerGroup) => {
          const hasContent = headerGroup.headers.some((header) => {
            const meta = header.column.columnDef.meta as
              ExtendedColumnMeta | undefined

            const isGroupHeader = header.subHeaders.length > 0

            if (isGroupHeader) {
              return (
                !header.isPlaceholder && meta?.hasExplicitGroupHeader === true
              )
            }

            return (
              !header.isPlaceholder &&
              hasVisibleHeaderLabel(header.column.columnDef.header) &&
              !meta?.isAutoGeneratedGroup
            )
          })

          if (!hasContent) return null

          const sortableIds = headerGroup.headers
            .filter((header) => !header.isPlaceholder)
            .map((header) => header.column.id)

          return (
            <tr key={headerGroup.id}>
              <SortableContext items={sortableIds}>
                {headerGroup.headers.map(
                  (header: Header<DataTableFeatures, TData, unknown>) => {
                    if (header.isPlaceholder) {
                      return (
                        <th
                          key={header.id}
                          colSpan={header.colSpan}
                          className="px-3 py-3"
                        />
                      )
                    }

                    const meta = header.column.columnDef.meta as
                      ExtendedColumnMeta | undefined
                    const showHandle =
                      hasVisibleHeaderLabel(header.column.columnDef.header) &&
                      !meta?.isAutoGeneratedGroup

                    return (
                      <HeaderCell
                        key={header.id}
                        header={header}
                        sorting={table.state.sorting}
                        showHandle={showHandle}
                        isDropTarget={
                          activeId !== null &&
                          dropTarget.id === header.column.id &&
                          activeId !== header.column.id
                        }
                        dropSide={dropTarget.side}
                        isDraggingSource={activeId === header.column.id}
                      />
                    )
                  }
                )}
              </SortableContext>
            </tr>
          )
        })}
      </thead>
    </DndContext>
  )
}
