export type DisplayMode = "dialog" | "sheet"

/**
 * Props passed to operation components
 */
export interface OperationComponentProps<TData> {
  data?: TData
  onSuccess: () => void
  onCancel: () => void
}

/**
 * Base configuration for any operation
 * IMPORTANT: Only ONE of component, api, or handler should be provided
 */
export interface BaseOperationConfig<TData = unknown> {
  /** Option 1: Custom React component for full UI control */
  component?: ComponentType<OperationComponentProps<TData>>

  /** Option 2: API endpoint configuration for server calls */
  api?: {
    endpoint: string | ((data: TData) => string)
    method?: "POST" | "PUT" | "DELETE" | "PATCH" // GET removed as it is not a mutation
    key: string | readonly unknown[]
    /** Tags to invalidate after successful mutation */
    revalidateTags?: string[]
    /** Extra headers - static or derived from the row (e.g. If-Match for OCC) */
    headers?: HeadersInit | ((data: TData) => HeadersInit)
    /**
     * Request body override. Defaults to the row data, except DELETE which
     * sends no body (Kittle and REST delete endpoints reject bodyful
     * DELETEs; the old factory ignored them). Provide explicitly for
     * bodyful deletes (e.g. confirmation handshakes).
     */
    body?: unknown
  }

  /** Option 3: Custom function handler for client-side logic */
  handler?: (data?: TData) => void | Promise<void>

  /** Optional: Confirmation settings */
  confirmation?: {
    title?: string
    message?: string
    confirmText?: string
    cancelText?: string
  }

  /** Display mode for component-based operations */
  displayMode?: DisplayMode

  /** Width size for sheet/dialog layouts. */
  width?: "sm" | "md" | "lg" | "xl" | "wide" | "full" | "detailSm" | "detailLg"

  /** Label for buttons (e.g. "Add User") */
  label?: string

  /**
   * Custom title for the modal (overrides auto-generated title). The function
   * form receives the row, so a sheet can name the record it is acting on —
   * "Align Subject Areas — CBSE 2026-27" instead of a bare action name.
   */
  modalTitle?: string | ((data: TData) => string)

  /** Custom description for the modal (overrides auto-generated description). */
  modalDescription?: string | ((data: TData) => string)

  icon?: ReactNode

  /** Custom color class for the dropdown menu item (overrides default color mapping) */
  colorClass?: string

  /** Optional RBAC/granular permission operation key override */
  permissionKey?: string

  /** Optional moduleKey override for RBAC/granular permission resolution */
  permissionModuleKey?: string

  /** Optional CASL action override for RBAC resolution */
  permissionAction?: string

  /** Optional CASL subject override for RBAC resolution */
  permissionSubject?: string

  /** Conditional display for row-level actions */
  isVisible?: (data: TData) => boolean

  /** Override modal requirement (default: true for component, false for handler) */
  requiresModal?: boolean
}

/**
 * Validated operation config - ensures only one execution method
 */
export type ValidatedOperationConfig<TData> =
  | {
      component: ComponentType<OperationComponentProps<TData>>
      api?: never
      handler?: never
    }
  | {
      api: NonNullable<BaseOperationConfig<TData>["api"]>
      component?: never
      handler?: never
    }
  | {
      handler: NonNullable<BaseOperationConfig<TData>["handler"]>
      component?: never
      api?: never
    }

/**
 * Complete operations registry
 */
export interface OperationsConfig<TData> {
  add?: BaseOperationConfig<TData>
  edit?: BaseOperationConfig<TData>
  view?: BaseOperationConfig<TData>
  delete?: BaseOperationConfig<TData>
  complete?: BaseOperationConfig<TData>
  dismiss?: BaseOperationConfig<TData>
  cancel?: BaseOperationConfig<TData>
  [key: string]: BaseOperationConfig<TData> | undefined
}

