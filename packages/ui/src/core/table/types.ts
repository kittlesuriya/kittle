export interface DataTableProps<TData extends RowWithId> {
  className?: string
  classNames?: DataTableClassNames
  partClassNames?: DataTablePartClassNames
  tag: string
  title: string
  subject?: string
  moduleKey?: string
  /** Optional separate module key for fetching documentation, defaults to moduleKey */
  docModuleKey?: string
  /** Width preset for the documentation drawer. Defaults to "md" (~576 px). */
  docDrawerWidth?: DocDrawerWidth
  translationNamespace?: string

  /** Data fetching configuration */
  fetchData: {
    endpoint: string
    method?: "GET" | "POST"
    key: string | readonly unknown[]
    params?: QueryParams
  }

  columnsConfig: ColumnGroup<TData>[]

  /**
   * Optional callback with the rows currently loaded into the table (the
   * active page). Lets a page run ONE batched read for per-row derived data —
   * alignment badge counts and the like — instead of a query per row. Called
   * only when the row set actually changes.
   */
  onRowsLoaded?: (rows: TData[]) => void

  /** Unified operations configuration (Row-level) */
  operations?: OperationsConfig<TData>

  /** Table-level bulk exports (PDF, CSV, Excel, etc.) */
  exports?: ExportsConfig<TData>

  organizationId?: string
  organizationRequired?: boolean
  scope?: "tenant" | "platform"
  filterConfig?: FilterConfig
  initialSorting?: SortingState

  /** Legacy or optional overrides */
  showPagination?: boolean
  /**
   * When false, TanStack performs client-side pagination over the full dataset it
   * receives from the server (used when the API returns every filtered row). Defaults
   * to true, where the server is responsible for page/row slicing.
   */
  manualPagination?: boolean
  dontShowColumnSelect?: boolean
  actionHeader?: string

  /**
   * Validation mode for operations
   * - 'strict': Throw errors if multiple execution methods provided (recommended)
   * - 'priority': Use priority order (component > api > handler) with warnings
   * @default 'strict'
   */
  validationMode?: "strict" | "priority"

  /**
   * Optional granular operation permissions. When present for a module they take
   * precedence over the CASL ability checks.
   * Format: { [moduleKey]: ["view", "edit", "customOperation"] }
   *
   * Example:
   * {
   *   "tenant.users": ["view", "edit", "delete"]
   * }
   *
   * Resolution order (see `useOperationPermissions.ts`):
   *   - `granularPermissions` undefined   -> CASL
   *   - no entry for this module key      -> CASL
   *   - entry present, operation listed    -> shown
   *   - entry present, operation NOT listed -> hidden
   *   - entry present but an empty array   -> ALL operations hidden
   *
   * The empty-array case is the trap: `[]` is truthy, so it counts as "this
   * module has granular permissions" and nothing survives the filter. Use an
   * absent key to mean "no override, fall back to CASL".
   *
   * NOTE: this previously referenced `docs/GRANULAR_PERMISSIONS.md`, which does
   * not exist. A full write-up of the session/ABAC model is still outstanding;
   * until then see `docs/architecture.md` and the `edtech-crud-navigation` skill.
   */
  granularPermissions?: GranularPermissions

  /** Optional custom content rendered above the table card (e.g. KPI summary) */
  topContent?: (context: {
    rows: TData[]
    rowCount: number
    table: ReactTable<DataTableFeatures, TData>
  }) => ReactNode
}

